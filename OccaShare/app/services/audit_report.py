import csv
import io
import textwrap
import zipfile
from xml.sax.saxutils import escape


REPORT_COLUMNS = (
    ("id", "Audit ID"),
    ("timestamp", "Timestamp"),
    ("actor", "Actor"),
    ("role", "Role"),
    ("action", "Action"),
    ("module", "Module"),
    ("old_status", "Old Status"),
    ("new_status", "New Status"),
    ("ip_address", "IP Address"),
    ("notes", "Details"),
)


def build_audit_csv(rows: list[dict], report_date: str, generated_by: str, filters: str) -> bytes:
    output = io.StringIO(newline="")
    writer = csv.writer(output)
    writer.writerow(["OccaServe System Audit Logs Report"])
    writer.writerow(["Generated on", report_date])
    writer.writerow(["Generated by", generated_by])
    writer.writerow(["Applied filters", filters])
    writer.writerow(["Matching log entries", len(rows)])
    writer.writerow([])
    writer.writerow([label for _, label in REPORT_COLUMNS])
    for row in rows:
        writer.writerow([_csv_safe(row.get(key, "")) for key, _ in REPORT_COLUMNS])
    return output.getvalue().encode("utf-8-sig")


def build_audit_docx(rows: list[dict], report_date: str, generated_by: str, filters: str) -> bytes:
    output = io.BytesIO()
    document_xml = _docx_document(rows, report_date, generated_by, filters)
    content_types = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
        '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>'
        '<Default Extension="xml" ContentType="application/xml"/>'
        '<Override PartName="/word/document.xml" '
        'ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>'
        '</Types>'
    )
    root_relationships = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
        '<Relationship Id="rId1" '
        'Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" '
        'Target="word/document.xml"/>'
        '</Relationships>'
    )
    with zipfile.ZipFile(output, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        archive.writestr("[Content_Types].xml", content_types)
        archive.writestr("_rels/.rels", root_relationships)
        archive.writestr("word/document.xml", document_xml)
    return output.getvalue()


def build_audit_pdf(rows: list[dict], report_date: str, generated_by: str, filters: str) -> bytes:
    report_lines = []
    for line in (
        "OccaServe System Audit Logs Report",
        f"Generated on: {report_date}",
        f"Generated by: {generated_by}",
        f"Applied filters: {filters}",
        f"Matching log entries: {len(rows)}",
        "",
    ):
        report_lines.extend(_wrapped_lines(line))
    for row in rows:
        for line in [
            f'#{row.get("id", "")} | {row.get("timestamp", "")} | {row.get("actor", "")} ({row.get("role", "")})',
            f'Action: {row.get("action", "")} | Module: {row.get("module", "")}',
            f'Old status: {row.get("old_status", "") or "Not recorded"} | '
            f'New status: {row.get("new_status", "") or "Not recorded"} | '
            f'IP: {row.get("ip_address", "") or "Not recorded"}',
        ]:
            report_lines.extend(_wrapped_lines(line))
        details = row.get("notes") or "No additional details recorded."
        for paragraph in str(details).splitlines() or [""]:
            report_lines.extend(_wrapped_lines(f"Details: {paragraph}"))
        report_lines.append("")

    lines_per_page = 40
    page_lines = [
        report_lines[offset:offset + lines_per_page]
        for offset in range(0, len(report_lines), lines_per_page)
    ] or [[]]
    streams = []
    for page_number, lines in enumerate(page_lines, start=1):
        content = []
        y = 570
        content.append(_pdf_text(36, y, f"OccaServe System Audit Logs - Page {page_number} of {len(page_lines)}", 10))
        y -= 18
        for line in lines:
            content.append(_pdf_text(36, y, line, 8))
            y -= 12
        streams.append("\n".join(content).encode("cp1252", "replace"))

    return _assemble_pdf(streams)


def build_sectioned_report_docx(
    title: str,
    report_date: str,
    sections: list[tuple[str, list[str], list[list[str]]]],
) -> bytes:
    output = io.BytesIO()
    body = [
        _docx_paragraph(title, "Title"),
        _docx_paragraph(f"Generated on: {report_date}"),
    ]
    for section_title, headers, rows in sections:
        body.append(_docx_paragraph(section_title, "Heading1"))
        if not rows:
            body.append(_docx_paragraph("No data available."))
            continue
        weights = [
            min(36, max(
                8,
                len(header) * 0.8,
                min(30, max((len(str(row[index])) for row in rows if index < len(row)), default=0) * 0.35),
            ))
            for index, header in enumerate(headers)
        ]
        total_weight = sum(weights) or 1
        widths = [int(15100 * weight / total_weight) for weight in weights]
        widths[-1] += 15100 - sum(widths)
        table_rows = [
            "<w:tr><w:trPr><w:tblHeader/></w:trPr>"
            + "".join(
                _docx_cell(value, width, header=True)
                for value, width in zip(headers, widths)
            )
            + "</w:tr>"
        ]
        table_rows.extend(
            "<w:tr>"
            + "".join(
                _docx_cell(value, width)
                for value, width in zip(row, widths)
            )
            + "</w:tr>"
            for row in rows
        )
        grid_columns = [f'<w:gridCol w:w="{width}"/>' for width in widths]
        table = (
            '<w:tbl><w:tblPr><w:tblW w:w="15100" w:type="dxa"/>'
            '<w:tblLayout w:type="fixed"/>'
            '<w:tblBorders>'
            '<w:top w:val="single" w:sz="4" w:color="CBD5E1"/>'
            '<w:left w:val="single" w:sz="4" w:color="CBD5E1"/>'
            '<w:bottom w:val="single" w:sz="4" w:color="CBD5E1"/>'
            '<w:right w:val="single" w:sz="4" w:color="CBD5E1"/>'
            '<w:insideH w:val="single" w:sz="4" w:color="CBD5E1"/>'
            '<w:insideV w:val="single" w:sz="4" w:color="CBD5E1"/>'
            '</w:tblBorders></w:tblPr>'
            f'<w:tblGrid>{"".join(grid_columns)}</w:tblGrid>'
            f'{"".join(table_rows)}</w:tbl>'
        )
        body.append(table)
    body.append(
        '<w:sectPr><w:pgSz w:w="16838" w:h="11906" w:orient="landscape"/>'
        '<w:pgMar w:top="500" w:right="500" w:bottom="500" w:left="500" '
        'w:header="250" w:footer="250" w:gutter="0"/></w:sectPr>'
    )
    document_xml = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">'
        f'<w:body>{"".join(body)}</w:body></w:document>'
    )
    content_types = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
        '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>'
        '<Default Extension="xml" ContentType="application/xml"/>'
        '<Override PartName="/word/document.xml" '
        'ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>'
        '</Types>'
    )
    root_relationships = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
        '<Relationship Id="rId1" '
        'Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" '
        'Target="word/document.xml"/>'
        '</Relationships>'
    )
    with zipfile.ZipFile(output, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        archive.writestr("[Content_Types].xml", content_types)
        archive.writestr("_rels/.rels", root_relationships)
        archive.writestr("word/document.xml", document_xml)
    return output.getvalue()


def build_sectioned_report_pdf(
    title: str,
    report_date: str,
    sections: list[tuple[str, list[str], list[list[str]]]],
) -> bytes:
    report_lines = _wrapped_lines(f"Generated on: {report_date}")
    report_lines.append("")
    for section_title, headers, rows in sections:
        report_lines.extend(_wrapped_lines(section_title))
        report_lines.extend(_wrapped_lines(" | ".join(headers)))
        report_lines.extend(_wrapped_lines("-" * min(140, max(24, len(" | ".join(headers))))))
        if rows:
            for row in rows:
                report_lines.extend(_wrapped_lines(" | ".join(row)))
        else:
            report_lines.extend(_wrapped_lines("No data available."))
        report_lines.append("")

    lines_per_page = 40
    page_lines = [
        report_lines[offset:offset + lines_per_page]
        for offset in range(0, len(report_lines), lines_per_page)
    ] or [[]]
    streams = []
    for page_number, lines in enumerate(page_lines, start=1):
        content = [_pdf_text(36, 570, f"{title} - Page {page_number} of {len(page_lines)}", 10)]
        y = 552
        for line in lines:
            content.append(_pdf_text(36, y, line, 8))
            y -= 12
        streams.append("\n".join(content).encode("cp1252", "replace"))
    return _assemble_pdf(streams)


def _wrapped_lines(value: str) -> list[str]:
    return textwrap.wrap(str(value), width=150, break_long_words=True, break_on_hyphens=True) or [""]


def _csv_safe(value) -> str:
    text = "" if value is None else str(value)
    if text.lstrip(" \t\r\n").startswith(("=", "+", "-", "@")):
        return "'" + text
    return text


def _docx_text(value) -> str:
    text = "" if value is None else str(value)
    text = "".join(
        character for character in text
        if character in "\t\n\r" or 0x20 <= ord(character) <= 0xD7FF
        or 0xE000 <= ord(character) <= 0xFFFD
        or 0x10000 <= ord(character) <= 0x10FFFF
    )
    return escape(text).replace("\n", "</w:t><w:br/><w:t>")


def _docx_paragraph(value: str, style: str | None = None) -> str:
    p_style = f'<w:pPr><w:pStyle w:val="{style}"/></w:pPr>' if style else ""
    return (
        f"<w:p>{p_style}<w:r><w:t xml:space=\"preserve\">"
        f"{_docx_text(value)}</w:t></w:r></w:p>"
    )


def _docx_cell(value: str, width: int, header: bool = False) -> str:
    shade = '<w:shd w:fill="1F2937"/>' if header else ""
    color = '<w:color w:val="FFFFFF"/>' if header else ""
    bold = "<w:b/>" if header else ""
    return (
        f'<w:tc><w:tcPr><w:tcW w:w="{width}" w:type="dxa"/>{shade}'
        '<w:tcMar><w:top w:w="70" w:type="dxa"/><w:left w:w="90" w:type="dxa"/>'
        '<w:bottom w:w="70" w:type="dxa"/><w:right w:w="90" w:type="dxa"/></w:tcMar></w:tcPr>'
        '<w:p><w:pPr><w:spacing w:before="0" w:after="0"/></w:pPr><w:r><w:rPr>'
        '<w:rFonts w:ascii="Arial" w:hAnsi="Arial"/><w:sz w:val="16"/>'
        f'{bold}{color}</w:rPr>'
        f'<w:t xml:space="preserve">{_docx_text(value)}</w:t></w:r></w:p></w:tc>'
    )


def _docx_document(rows: list[dict], report_date: str, generated_by: str, filters: str) -> str:
    widths = (800, 1500, 1700, 800, 1500, 1100, 1200, 1200, 1300, 4000)
    table_rows = []
    header_cells = "".join(
        _docx_cell(label, width, header=True)
        for (_, label), width in zip(REPORT_COLUMNS, widths)
    )
    table_rows.append(f"<w:tr><w:trPr><w:tblHeader/></w:trPr>{header_cells}</w:tr>")
    for row in rows:
        cells = "".join(
            _docx_cell(str(row.get(key, "") or ""), width)
            for (key, _), width in zip(REPORT_COLUMNS, widths)
        )
        table_rows.append(f"<w:tr>{cells}</w:tr>")
    grid = "".join(f'<w:gridCol w:w="{width}"/>' for width in widths)
    table = (
        '<w:tbl><w:tblPr><w:tblW w:w="15100" w:type="dxa"/>'
        '<w:tblLayout w:type="fixed"/>'
        '<w:tblBorders>'
        '<w:top w:val="single" w:sz="4" w:color="CBD5E1"/>'
        '<w:left w:val="single" w:sz="4" w:color="CBD5E1"/>'
        '<w:bottom w:val="single" w:sz="4" w:color="CBD5E1"/>'
        '<w:right w:val="single" w:sz="4" w:color="CBD5E1"/>'
        '<w:insideH w:val="single" w:sz="4" w:color="CBD5E1"/>'
        '<w:insideV w:val="single" w:sz="4" w:color="CBD5E1"/>'
        '</w:tblBorders></w:tblPr>'
        f"<w:tblGrid>{grid}</w:tblGrid>{''.join(table_rows)}</w:tbl>"
    )
    body = "".join([
        _docx_paragraph("OccaServe System Audit Logs Report", "Title"),
        _docx_paragraph(f"Generated on: {report_date}"),
        _docx_paragraph(f"Generated by: {generated_by}"),
        _docx_paragraph(f"Applied filters: {filters}"),
        _docx_paragraph(f"Matching log entries: {len(rows)}"),
        table,
        '<w:sectPr><w:pgSz w:w="16838" w:h="11906" w:orient="landscape"/>'
        '<w:pgMar w:top="500" w:right="500" w:bottom="500" w:left="500" '
        'w:header="250" w:footer="250" w:gutter="0"/></w:sectPr>',
    ])
    return (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">'
        f"<w:body>{body}</w:body></w:document>"
    )


def _pdf_text(x: int, y: int, value: str, size: int) -> str:
    text = "".join(
        character if character == "\t" or ord(character) >= 32 else " "
        for character in str(value)
    ).encode("cp1252", "replace").decode("cp1252")
    escaped = text.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")
    escaped = escaped.replace("\r", " ").replace("\n", " ")
    return f"BT /F1 {size} Tf {x} {y} Td ({escaped}) Tj ET"


def _assemble_pdf(streams: list[bytes]) -> bytes:
    page_ids = [4 + index * 2 for index in range(len(streams))]
    kids = " ".join(f"{page_id} 0 R" for page_id in page_ids)
    objects = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        f"<< /Type /Pages /Kids [{kids}] /Count {len(streams)} >>".encode("ascii"),
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>",
    ]
    for page_id, stream in zip(page_ids, streams):
        content_id = page_id + 1
        objects.extend([
            (
                f"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 792 612] "
                f"/Resources << /Font << /F1 3 0 R >> >> /Contents {content_id} 0 R >>"
            ).encode("ascii"),
            f"<< /Length {len(stream)} >>\nstream\n".encode("ascii") + stream + b"\nendstream",
        ])

    output = bytearray(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
    offsets = [0]
    for object_id, body in enumerate(objects, start=1):
        offsets.append(len(output))
        output.extend(f"{object_id} 0 obj\n".encode("ascii"))
        output.extend(body)
        output.extend(b"\nendobj\n")

    xref_offset = len(output)
    output.extend(f"xref\n0 {len(objects) + 1}\n".encode("ascii"))
    output.extend(b"0000000000 65535 f \n")
    for offset in offsets[1:]:
        output.extend(f"{offset:010d} 00000 n \n".encode("ascii"))
    output.extend(
        f"trailer\n<< /Size {len(objects) + 1} /Root 1 0 R >>\n"
        f"startxref\n{xref_offset}\n%%EOF\n".encode("ascii")
    )
    return bytes(output)
