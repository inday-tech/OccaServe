import io
import re
import zipfile
from xml.etree import ElementTree

from app.services.audit_report import build_audit_docx, build_audit_pdf


def make_audit_row(row_id: int) -> dict:
    return {
        "id": row_id,
        "timestamp": f"2026-11-01 10:{row_id % 60:02}:00",
        "actor": f"Admin {row_id}",
        "role": "Admin",
        "action": "Account updated",
        "module": "Users",
        "old_status": "pending",
        "new_status": "active",
        "ip_address": "192.0.2.1",
        "notes": f"Full audit details for entry {row_id}.",
    }


def test_word_export_is_valid_docx_and_contains_every_record():
    rows = [make_audit_row(row_id) for row_id in range(1, 4)]

    content = build_audit_docx(rows, "Nov 01, 2026 10:00 AM PHT", "Admin User", "All audit logs")
    with zipfile.ZipFile(io.BytesIO(content)) as archive:
        document_xml = archive.read("word/document.xml")
        ElementTree.fromstring(document_xml)
        document = document_xml.decode("utf-8")
        assert document.count("<w:tr>") == len(rows) + 1
        assert "Full audit details for entry 3." in document
        assert "Generated by: Admin User" in document
        assert 'w:orient="landscape"' in document
        assert '<w:tblLayout w:type="fixed"/>' in document
        assert "<w:tcMar>" in document


def test_pdf_export_has_valid_xref_and_all_records_across_pages():
    rows = [make_audit_row(row_id) for row_id in range(1, 31)]

    content = build_audit_pdf(rows, "Nov 01, 2026 10:00 AM PHT", "Admin User", "All audit logs")
    xref_offset = int(re.search(rb"startxref\n(\d+)\n%%EOF", content).group(1))

    assert content.startswith(b"%PDF-1.4")
    assert content[xref_offset:xref_offset + 4] == b"xref"
    assert b"Page 1 of " in content
    assert b"Full audit details for entry 30." in content
    assert b"Matching log entries: 30" in content
